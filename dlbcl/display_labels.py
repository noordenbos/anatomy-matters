"""Manuscript display labels without modifying stored calls or analysis keys.

Call ``finalize_figure_labels`` before exporting/previewing a Matplotlib figure.
COO labels require explicit classifier context: Ciavarella Intermediate and
confidence-interval abbreviations must remain unchanged.
"""

from __future__ import annotations

import re

from .classifier_colors import classifier_key

FIGURE_3D_TITLE = "Differentially expressed genes"
ARCHETYPE_SHORT_LABELS = {
    "low immune": "LI", "cytotoxic predominant": "CP", "complex immune": "DI",
}


def display_text(value) -> str:
    """Update the archetype name in prose/labels, preserving 95% CI notation."""
    text = str(value)
    return re.sub(
        r"(?<![A-Za-z])complex immune(?![A-Za-z])",
        lambda m: "Diverse immune" if m.group()[0].isupper() else "diverse immune",
        text, flags=re.IGNORECASE,
    )


def classifier_display_label(classifier: str, value) -> str:
    """Format a classifier-specific label, without recoding its stored value."""
    label = str(value)
    coo = classifier_key(classifier) == "lymph2cx_coo" or str(classifier).strip().casefold() in {"coo", "cell of origin", "lymph2cx"}
    if coo and label.strip().casefold() == "intermediate":
        return "Unclassified"
    return display_text(label)


def finalize_figure_labels(fig, *, classifier: str | None = None):
    """Update only figure text; preserve all plotted values and source objects.

    Tick formatters are wrapped only if their current labels need changing,
    so a later draw cannot restore an old categorical label. Numeric formatters
    and colorbar scales are untouched. Repeated calls are safe.
    """
    from matplotlib.text import Text
    from matplotlib.ticker import FuncFormatter

    def transform(value):
        return classifier_display_label(classifier, value) if classifier else display_text(value)

    # Tick labels are regenerated by Axis.draw, unlike ordinary Text artists.
    for ax in fig.axes:
        for axis in (ax.xaxis, ax.yaxis):
            labels = axis.get_majorticklabels()
            if any(transform(label.get_text()) != label.get_text() for label in labels):
                original = axis.get_major_formatter()
                axis.set_major_formatter(FuncFormatter(
                    lambda value, pos, original=original: transform(original(value, pos))
                ))
    for artist in fig.findobj(match=Text):
        old = artist.get_text()
        new = transform(old)
        if new != old:
            artist.set_text(new)
    return fig
